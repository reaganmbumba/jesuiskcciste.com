export const parishCountryLabel = (c: ParishCountry, locale: Locale) => PARISH_COUNTRIES[c][locale];

/** « Kinshasa, RD Congo » ou « Angola ». */
export const parishPlaceLabel = (p: OfficialParish, locale: Locale) =>
  p.region ? `${p.region[locale]}, ${PARISH_COUNTRIES[p.country][locale]}` : PARISH_COUNTRIES[p.country][locale];
